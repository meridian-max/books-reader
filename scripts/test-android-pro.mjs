import assert from "node:assert/strict";
import { execFileSync, spawn } from "node:child_process";
import { mkdtemp, readFile, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { createHash } from "node:crypto";
import { connect } from "./android-cdp.mjs";
const adb = "/home/divyansh/Downloads/Rishikes/rishikesh-mobile/native-builds/local-toolchain/android-sdk/platform-tools/adb";
const temporary = await mkdtemp(path.join(tmpdir(), "books-ftp-test-"));
const expected = Buffer.from("FTP integration fixture, Books 1.1.0.\n\nA real passive binary download must keep every byte intact.\n");
await writeFile(path.join(temporary, "ftp-reading.txt"), expected);
execFileSync("openssl", ["req", "-x509", "-newkey", "rsa:2048", "-nodes", "-keyout", temporary + "/key.pem", "-out", temporary + "/cert.pem", "-days", "1", "-subj", "/CN=10.0.2.2", "-addext", "subjectAltName=IP:10.0.2.2"], { stdio: "ignore" });
const server = spawn(process.env.BOOKS_TEST_PYTHON || "python3", ["scripts/ftp-fixture.py", temporary, temporary + "/cert.pem", temporary + "/key.pem"], { stdio: ["ignore", "pipe", "pipe"] });
const ready = new Promise((resolve, reject) => {
  const timer = setTimeout(() => reject(Error("FTP fixture startup timed out")), 10000);
  server.stdout.on("data", chunk => { if (String(chunk).includes("FIXTURE_READY")) { clearTimeout(timer); resolve(); } });
  server.once("exit", code => { clearTimeout(timer); reject(Error("FTP fixture exited: " + code)); });
});
const c = await connect(), results = [];
let originalFtp, originalReadwise;
const fill = (selector, value) => c.evaluate(({selector,value}) => { const el = document.querySelector(selector); el.value = value; el.dispatchEvent(new Event("input",{bubbles:true})); }, {selector,value});
try {
  await ready;
  await c.send("Page.reload");
  await c.poll(() => !!document.querySelector("[data-action=mobile-menu]"));
  originalFtp = await c.native("getFtp"); originalReadwise = await c.native("getReadwise");
  await c.native("clearFtp");
  await c.click("[data-action=ftp]");
  await fill("#ftp-connect [name=host]", "10.0.2.2");
  await fill("#ftp-connect [name=port]", "2121");
  await fill("#ftp-connect [name=username]", "books-test");
  await fill("#ftp-connect [name=password]", "books-transfer-fixture");
  await c.evaluate(() => document.querySelector("#ftp-connect [name=tls]").checked = false);
  await c.click("#ftp-connect button[type=submit]");
  await c.poll(() => !!document.querySelector(".ftp-file"));
  const config = await c.native("getFtp");
  const listing = await c.native("ftp", { operation:"list", path:"/" });
  assert.ok(listing.entries.some(x => x.name === "ftp-reading.txt"));
  results.push({name:"UI FTP login and passive directory listing",status:"passed"});
  const record = await c.native("ftp", { operation:"download", path:"/ftp-reading.txt" });
  const downloaded = await c.evaluate(async url => Array.from(new Uint8Array(await (await fetch(url)).arrayBuffer())), record.url);
  assert.deepEqual(Buffer.from(downloaded),expected);
  results.push({name:"binary FTP download",status:"passed",sha256:createHash("sha256").update(expected).digest("hex")});
  const uploaded = Buffer.from([0,255,127,42,13,10]);
  await c.native("ftp",{operation:"upload",path:"/uploaded.bin",base64:uploaded.toString("base64")});
  assert.deepEqual(await readFile(path.join(temporary,"uploaded.bin")),uploaded);
  await assert.rejects(c.native("ftp",{operation:"upload",path:"/uploaded.bin",base64:"AA=="}), /already exists/);
  await c.native("ftp",{operation:"mkdir",path:"/books-folder"});
  await c.native("ftp",{operation:"rename",path:"/uploaded.bin",destination:"/books-folder/renamed.bin"});
  assert.deepEqual(await readFile(path.join(temporary,"books-folder/renamed.bin")),uploaded);
  await c.native("ftp",{operation:"delete",path:"/books-folder/renamed.bin"});
  await c.native("ftp",{operation:"delete",path:"/books-folder",directory:true});
  results.push({name:"FTP upload, overwrite rejection, mkdir, rename and delete",status:"passed"});
  await assert.rejects(c.native("ftp",{operation:"list",path:"/",config:{...config,password:"incorrect"}}), /login failed/);
  await assert.rejects(c.native("ftp",{operation:"list",path:"/\r\nDELE ftp-reading.txt"}), /control characters/);
  await assert.rejects(c.native("ftp",{operation:"list",path:"/",config:{...config,port:2122,tls:true}}), /trust|certificate|CertPath|SSL|handshake/i);
  assert.deepEqual(await readFile(path.join(temporary,"ftp-reading.txt")),expected);
  results.push({name:"FTP invalid login, command injection and untrusted FTPS certificate rejected",status:"passed"});
  await c.native("setReadwise",{token:"readwise-storage-fixture"});
  assert.equal((await c.native("getReadwise")).token,"readwise-storage-fixture");
  const preferences = execFileSync(adb,["-s","emulator-5570","shell","run-as","app.books.reader","cat","shared_prefs/books.xml"],{encoding:"utf8"});
  assert.ok(!preferences.includes("readwise-storage-fixture"));
  assert.ok(!preferences.includes("books-transfer-fixture"));
  results.push({name:"FTP and Readwise secrets roundtrip with encrypted preferences",status:"passed"});
  await c.evaluate(() => [...document.querySelectorAll("[data-ftp-open]")].find(x=>x.textContent.includes("ftp-reading.txt")).click());
  await c.poll(() => [...document.querySelectorAll(".book-title")].some(x=>x.textContent.includes("ftp-reading")));
  await c.screenshot("docs/screenshots/android-ftp-import-1.1.0.png");
  await c.evaluate(() => [...document.querySelectorAll(".book-title")].find(x=>x.textContent.includes("ftp-reading")).click());
  await c.poll(() => document.querySelector("foliate-view")?.renderer?.getContents()[0]?.doc.body.textContent.includes("must keep every byte intact"));
  await c.click("[data-action=exit]");
  await c.poll(() => !document.body.classList.contains("reading"));
  results.push({name:"UI FTP download imports and opens readable book content",status:"passed"});
  await writeFile("docs/android-pro-results.json",JSON.stringify({at:new Date().toISOString(),version:"1.1.0",device:"Android 15 x86_64 emulator",results},null,2)+"\n");
  console.log(JSON.stringify(results,null,2));
} finally {
  if (originalFtp !== undefined) await c.native(originalFtp ? "setFtp" : "clearFtp",originalFtp || {});
  if (originalReadwise !== undefined) await c.native(originalReadwise ? "setReadwise" : "clearReadwise",originalReadwise || {});
  c.close(); server.kill(); await rm(temporary,{recursive:true,force:true});
}
