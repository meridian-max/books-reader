function localize(root: Node) {
  if (isExcluded(root)) return;
  const walker = document.createTreeWalker(
      root,
      NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT,
      {
        acceptNode: (node) =>
          node instanceof Element
            ? node.matches(excluded)
              ? NodeFilter.FILTER_REJECT
              : NodeFilter.FILTER_SKIP
            : NodeFilter.FILTER_ACCEPT,
      },
    ),
    nodes: Text[] = [];
  if (root.nodeType === Node.TEXT_NODE) nodes.push(root as Text);
  while (walker.nextNode()) nodes.push(walker.currentNode as Text);
  for (const node of nodes) {
    const saved = originals.get(node),
      source = saved && node.data === saved.last ? saved.source : node.data;
    const text = source.trim(),
      replacement = translate(text),
      value = source.replace(text, replacement);
    if (node.data !== value) node.data = value;
    originals.set(node, { source, last: value });
  }
  const elements =
    root instanceof Element
      ? [root, ...root.querySelectorAll("[aria-label],[placeholder]")]
      : root instanceof Document
        ? [...root.querySelectorAll("[aria-label],[placeholder]")]
        : [];
  for (const el of elements)
    if (!isExcluded(el))
      for (const key of ["aria-label", "placeholder"]) {
        const value = el.getAttribute(key);
        if (value === null) continue;
        const saved = attributes.get(el) ?? new Map(),
          old = saved.get(key),
          source = old && old.last === value ? old.source : value,
          last = translate(source);
        if (last !== value) el.setAttribute(key, last);
        saved.set(key, { source, last });
        attributes.set(el, saved);
      }
}
